export function buildPySparkCode(config: PipelineConfig, sources: string[], sinks: string[]): string {
  const source = sources[0] ?? 'postgres_prod.ecommerce.orders';
  const target = sinks[0] ?? 'ANALYTICS_PROD.MART_ORDERS';
  const maskingBlock = config.piiMaskingEnabled
    ? `
# --- PII Tokenization (GDPR / CCPA) ---
from pyspark.sql import functions as F

EMAIL_SALT = dbutils.secrets.get("aiden-vault", "pii-salt")
df = df.withColumn(
    "customer_email_hash",
    F.sha2(F.concat(F.col("customer_email"), F.lit(EMAIL_SALT)), 256),
).drop("customer_email")`
    : '';

  const dqBlock = config.qualityChecksEnabled
    ? `
# --- Quality Gate (Great Expectations) ---
from great_expectations.dataset import SparkDFDataset

ge_dataset = SparkDFDataset(df)
ge_dataset.expect_column_values_to_not_be_null("order_id")
ge_dataset.expect_column_values_to_be_unique("order_id")
ge_dataset.expect_column_values_to_meet_date_range("gross_amount_usd", 0.0, None)
violations = ge_dataset.validate()["statistics"]["unsuccessful_expectations"]
if violations > 0:
    raise ValueError(f"Quality gate failed with {violations} expectation violations — halting write.")`
    : '';

  return `"""
${config.pipelineName} — generated by AIDEN Pipeline Builder
Execution mode: ${config.executionMode}
Source: ${source}
Target: ${target}
Write strategy: ${config.writeStrategy}
SLA freshness: ${config.slaFreshnessMinutes} minutes
"""

from pyspark.sql import SparkSession
from pyspark.sql import functions as F

spark = (
    SparkSession.builder
    .appName("${config.pipelineName}")
    .config("spark.sql.shuffle.partitions", "64")
    .config("spark.streaming.backpressure.enabled", "true")
    .getOrCreate()
)

# --- Source Ingestion ---
df = (
    spark.read
    .format("jdbc")
    .option("url", "jdbc:postgresql://postgres-prod.acme.internal:5432/ecommerce")
    .option("dbtable", "public.orders")
    .option("user", dbutils.secrets.get("aiden-vault", "pg-user"))
    .option("password", dbutils.secrets.get("aiden-vault", "pg-password"))
    .load()
)
${maskingBlock}

# --- Transformations ---
df = (
    df
    .withColumnRenamed("id", "order_id")
    .withColumn("gross_amount_usd", F.col("gross_amount_cents") / 100.0)
    .withColumn("ingested_at", F.current_timestamp())
    .filter(F.col("status").isin("pending", "paid", "shipped", "delivered", "refunded"))
)
${dqBlock}

# --- Sink Write (${config.writeStrategy}) ---
MERGE_KEYS = ["order_id"]
TEMP_VIEW = "${config.pipelineName}_staging"
df.createOrReplaceTempView(TEMP_VIEW)

spark.sql(f"""
    MERGE INTO ${target} AS tgt
    USING {TEMP_VIEW} AS src
    ON tgt.order_id = src.order_id
    WHEN MATCHED THEN UPDATE SET *
    WHEN NOT MATCHED THEN INSERT *
""")

# --- Monitoring hooks ---
spark.streams.awaitAnyTermination()
`;
}

export function buildSqlCode(config: PipelineConfig, sinks: string[]): string {
  const target = sinks[0] ?? 'ANALYTICS_PROD.MART_ORDERS';

  return `-- ${config.pipelineName} — Snowflake MERGE generated by AIDEN
-- Write strategy: ${config.writeStrategy}

MERGE INTO ${target} AS tgt
USING (
    SELECT
        order_id,
        customer_id,
        gross_amount_usd,
        currency_code,
        order_status,
        order_timestamp,
        customer_email_hash,${config.piiMaskingEnabled ? '\n        -- PII masked upstream (SHA-256 salted)' : ''}
        ingested_at
    FROM ${config.pipelineName.toUpperCase()}_STAGING
    WHERE _dedupe_rank = 1  -- latest event per order_id
) AS src
ON tgt.order_id = src.order_id
WHEN MATCHED AND tgt.order_status <> src.order_status THEN UPDATE SET *
WHEN NOT MATCHED THEN INSERT *;${config.qualityChecksEnabled ? `

-- Post-write quality assertions (fail the task on violation)
ALTER TASK ${config.pipelineName}_qa RESUME;
CALL ASSERT_NO_DUPLICATES('${target}', 'order_id');
CALL ASSERT_FRESHNESS('${target}', 'order_timestamp', ${config.slaFreshnessMinutes});` : ''}
`;
}

export function buildAirflowDag(config: PipelineConfig): string {
  const schedule = config.schedule === 'continuous' ? None_DAG_SCHEDULE : `'@${config.schedule}'`;

  return `"""
${config.pipelineName} — Airflow DAG generated by AIDEN Pipeline Builder
"""

from datetime import datetime, timedelta
from airflow import DAG
from airflow.operators.python import PythonOperator
from airflow.providers.databricks.operators.databricks import DatabricksSubmitRunOperator

default_args = {
    "owner": "aiden",
    "retries": ${config.retryPolicy.maxRetries},
    "retry_delay": timedelta(minutes=1),
    "retry_exponential_backoff": ${config.retryPolicy.backoff === 'exponential' ? 'True' : 'False'},
    "execution_timeout": timedelta(minutes=${config.retryPolicy.timeoutMinutes}),
    "on_failure_callback": notify_${config.alertingChannel},
}

with DAG(
    dag_id="${config.pipelineName}",
    description="AIDEN generated ${config.executionMode} pipeline",
    schedule_interval=${schedule},
    start_date=datetime(2026, 1, 1),
    catchup=False,
    max_active_runs=1,
    tags=["aiden", "${config.executionMode}"],
) as dag:

    submit_spark_job = DatabricksSubmitRunOperator(
        task_id="run_${config.pipelineName}",
        existing_cluster_id="aiden-prod-cluster",
        notebook_task={
            "notebook_path": "/Repos/PROD/pipelines/${config.pipelineName}",
        },
    )

    run_quality_gate = PythonOperator(
        task_id="quality_gate",
        python_callable=run_quality_checks,${config.qualityChecksEnabled ? '' : '\n        # disabled in pipeline configuration'}
    )

    submit_spark_job >> run_quality_gate
`;
}

