export function buildTestSuite(config: PipelineConfig, sources: string[]): string {
  const source = sources[0] ?? 'ecommerce.orders';

  return `"""
${config.pipelineName} — pytest unit tests generated by AIDEN Pipeline Builder
Covers: schema conformance, PII masking, write strategy, idempotency.
"""

import pytest
import { PipelineConfig } from '../types';
import { GeneratedFile } from '../types';
from chispa import assert_df_equality
from pipelines.${config.pipelineName} import transform, apply_pii_masking


@pytest.fixture
def sample_orders(spark):
    return spark.createDataFrame(
        [
            ("ord-001", "cust-42", 12999, "paid"),
            ("ord-002", "cust-7", 0, "pending"),
        ],
        ["id", "customer_id", "gross_amount_cents", "status"],
    )


def test_schema_conformance(sample_orders):
    result = transform(sample_orders)
    expected_columns = {"order_id", "customer_id", "gross_amount_usd", "ingested_at"}
    assert expected_columns.issubset(set(result.columns))


def test_amount_conversion(sample_orders):
    result = transform(sample_orders)
    row = result.filter("order_id = 'ord-001'").first()
    assert row.gross_amount_usd == pytest.approx(129.99)
${config.piiMaskingEnabled ? `
def test_pii_email_is_masked(sample_orders):
    result = apply_pii_masking(sample_orders)
    assert "customer_email" not in result.columns
    assert "customer_email_hash" in result.columns` : ''}

def test_idempotent_merge(spark):
    """Replaying the same batch must not duplicate rows in ${source} target."""
    before = spark.sql(f"SELECT COUNT(*) FROM TARGET").first()[0]
    run_merge(batch_id=1)
    run_merge(batch_id=1)
    after = spark.sql(f"SELECT COUNT(*) FROM TARGET").first()[0]
    assert before + 1 == after
`;
}

export function buildAllFiles(config: PipelineConfig, sources: string[], sinks: string[]): GeneratedFile[] {
  const pyspark = buildPySparkCode(config, sources, sinks);
  const sql = buildSqlCode(config, sinks);
  const dag = buildAirflowDag(config);
  const kafka = buildKafkaConfig(config);
  const tests = buildTestSuite(config, sources);

  return [
    { target: 'pyspark', fileName: `${config.pipelineName}_job.py`, language: 'python', content: pyspark, lineCount: pyspark.split('\n').length },
    { target: 'sql', fileName: `${config.pipelineName}_merge.sql`, language: 'sql', content: sql, lineCount: sql.split('\n').length },
    { target: 'airflow_dag', fileName: `${config.pipelineName}_dag.py`, language: 'python', content: dag, lineCount: dag.split('\n').length },
    { target: 'kafka_config', fileName: `${config.pipelineName}_consumer.yaml`, language: 'yaml', content: kafka, lineCount: kafka.split('\n').length },
    { target: 'tests', fileName: `test_${config.pipelineName}.py`, language: 'python', content: tests, lineCount: tests.split('\n').length },
  ];
}
