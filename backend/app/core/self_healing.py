class FailureCategory(str, Enum):
    """High-level categories that the RCA maps errors into."""

    SCHEMA_DRIFT = "schema_drift"
    DATA_QUALITY = "data_quality"
    PERFORMANCE = "performance"
    CONNECTION = "connection"
    CODE_ERROR = "code_error"
    UNKNOWN = "unknown"


@dataclass
class HealingDiagnosis:
    """Result of the root-cause analysis step."""

    category: FailureCategory
    summary: str                         # Human-readable one-liner
    detail: str                          # Longer technical explanation
    confidence: float                    # 0.0 – 1.0
    error_snippet: str                   # The error text that was matched
    affected_columns: List[str] = field(default_factory=list)
    source_tables: List[str] = field(default_factory=list)


@dataclass
class HealingFix:
    """A proposed fix generated by the engine."""

    action: str                          # e.g. "update_query", "retry_with_backoff"
    description: str                     # Human-readable description of the fix
    config_patch: Optional[Dict[str, Any]] = None  # Partial pipeline.config update
    code_patch: Optional[str] = None     # Partial DAG/code replacement
    message: str = ""                    # Log-friendly detail

    def to_dict(self) -> Dict[str, Any]:
        return {
            "action": self.action,
            "description": self.description,
            "config_patch": self.config_patch,
            "code_patch": self.code_patch,
            "message": self.message,
        }


@dataclass
class HealingResult:
    """Complete result returned by :meth:`SelfHealingEngine.diagnose_and_heal`."""

    diagnosis: HealingDiagnosis
    fix: Optional[HealingFix] = None
    risk: RiskLevel = RiskLevel.LOW
    approval_id: Optional[int] = None    # Set if an approval record was created
    auto_applied: bool = False           # True when LOW-risk fix was applied
    error: Optional[str] = None          # Set if the engine itself failed


