"""
Self-Healing Engine — Automatic Failure Diagnosis & Recovery
============================================================

Detects pipeline execution failures, diagnoses root causes,
proposes fixes, assesses risk, and drives the approval workflow.

Architecture:

    ┌────────────────────────────────────────────────────────────────┐
    │  SelfHealingEngine                                            │
    │                                                                │
    │  1. FAILURE DETECTION                                          │
    │     └── Error message pattern matching                         │
    │                                                                │
    │  2. ROOT CAUSE ANALYSIS                                        │
    │     ├── Schema Drift   — column(s) added/renamed/dropped       │
    │     ├── Data Quality   — nulls, duplicates, format issues      │
    │     ├── Performance    — timeouts, resource exhaustion         │
    │     ├── Connection     — database/API unreachable              │
    │     └── Code Error     — syntax, logic bugs in generated DAG   │
    │                                                                │
    │  3. FIX PROPOSAL (rule-based + optional LLM)                   │
    │     └── Generates a structured fix for the diagnosed problem   │
    │                                                                │
    │  4. RISK ASSESSMENT                                            │
    │     ├── LOW       — Auto-apply, no approval needed             │
    │     ├── MEDIUM    — Suggest fix, auto-approve after 5 min      │
    │     ├── HIGH      — Create approval, human must approve        │
    │     └── CRITICAL  — Create approval, page on-call              │
    │                                                                │
    │  5. FIX APPLICATION                                            │
    │     └── Apply fix → Update pipeline config → Re-run           │
    │                                                                │
    │  6. LEARNING                                                    │
    │     └── Store fix + outcome in RAG memory for future           │
    └────────────────────────────────────────────────────────────────┘
"""

