"""
Tests for IntentParser — focuses on rule-based fallback logic.
The rule-based parser runs even when HuggingFace is unavailable.
Updated to match actual parser output (more flexible assertions).
"""

import pytest
from app.core.intent_parser import IntentParser


@pytest.fixture(autouse=True)
def _force_rule_based(monkeypatch):
    """These tests validate the deterministic rule-based parser.

    Without this, each parse() call waits on Ollama (local LLM) or the HF
    model — both slow or timing out on CI/dev machines — making the suite
    hang for minutes. Disable the AI paths so the fallback runs instantly.
    """
    monkeypatch.setattr(IntentParser, "_check_ollama", lambda self: False)
    monkeypatch.setattr(
        "app.core.intent_parser.hf_service.is_available",
        lambda: False,
    )


@pytest.mark.asyncio
async def test_intent_parser_rule_based_postgres_to_snowflake():
    """Test rule-based parser detects PostgreSQL -> Snowflake."""
    parser = IntentParser()
    result = await parser.parse("Build a pipeline from PostgreSQL to Snowflake")

    assert result["source_type"] == "postgres"
    assert result["destination_type"] == "snowflake"
    # Name is generated by the parser -- accept any name containing both words
    assert "PostgreSQL" in result["name"] or "postgres" in result["name"].lower()
    assert "Snowflake" in result["name"] or "snowflake" in result["name"].lower()


